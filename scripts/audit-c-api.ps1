[CmdletBinding()]
param(
	[string]$ReposRoot = (Join-Path $PSScriptRoot '..'),
	[string]$OutputPath = (Join-Path $PSScriptRoot '..\PHASE10_API_INVENTORY.md'),
	[string]$CategoryOutputPath = (Join-Path $PSScriptRoot '..\PHASE10_API_CATEGORIES.md')
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$projectRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path

$modules = @(
	@{ Name = 'QuantumCore'; Prefix = 'quantum'; Header = 'quantum_c_api.h'; Source = 'quantum_c_api.cpp' },
	@{ Name = 'ClassicalMechanicsCore'; Prefix = 'classical'; Header = 'classical_c_api.h'; Source = 'classical_c_api.cpp' },
	@{ Name = 'ElectrodynamicsCore'; Prefix = 'em'; Header = 'em_c_api.h'; Source = 'em_c_api.cpp' },
	@{ Name = 'FluidDynamicsCore'; Prefix = 'fluid'; Header = 'fluid_c_api.h'; Source = 'fluid_c_api.cpp' },
	@{ Name = 'NuclearCore'; Prefix = 'nuclear'; Header = 'nuclear_c_api.h'; Source = 'nuclear_c_api.cpp' },
	@{ Name = 'OpticsCore'; Prefix = 'optics'; Header = 'optics_c_api.h'; Source = 'optics_c_api.cpp' },
	@{ Name = 'SolidStateCore'; Prefix = 'solidstate'; Header = 'solidstate_c_api.h'; Source = 'solidstate_c_api.cpp' },
	@{ Name = 'ThermodynamicsCore'; Prefix = 'thermo'; Header = 'thermo_c_api.h'; Source = 'thermo_c_api.cpp' }
)

function Remove-CppCommentsAndStrings([string]$Text) {
	$Text = [regex]::Replace($Text, '/\*.*?\*/', '', [Text.RegularExpressions.RegexOptions]::Singleline)
	$Text = [regex]::Replace($Text, '//[^\r\n]*', '')
	$Text = [regex]::Replace($Text, '"(?:\\.|[^"\\])*"', '""')
	return $Text
}

function Get-FunctionNames([string]$Path, [ValidateSet('Declaration', 'Definition')][string]$Kind) {
	$raw = Get-Content -Raw -LiteralPath $Path
	$text = Remove-CppCommentsAndStrings $raw
	$pattern = '(?ms)(?:^|[;{}])\s*(?:(?:extern\s+"C"|inline|static|const|constexpr|[A-Z_][A-Z0-9_]*_API)\s+)*[A-Za-z_][\w:\s\*&<>]*?\b([A-Za-z_]\w*)\s*\((.*?)\)\s*(?:const\s*)?(?<terminator>;|\{)'
	$names = [System.Collections.Generic.List[string]]::new()
	foreach ($match in [regex]::Matches($text, $pattern)) {
		$terminator = $match.Groups['terminator'].Value
		if (($Kind -eq 'Declaration' -and $terminator -ne ';') -or
			($Kind -eq 'Definition' -and $terminator -ne '{')) {
			continue
		}

		$name = $match.Groups[1].Value
		if ($name -notmatch '^(qp|cp|em|fluid|np|op|ss|td)_') {
			continue
		}
		if (-not $names.Contains($name)) {
			$names.Add($name)
		}
	}
	return @($names | Sort-Object)
}

function Get-ApiCategory([string]$Name) {
	if ($Name -match '_(create|destroy|init|initialize|reset|set|configure|update|get_[a-z0-9_]+)$') {
		return 'lifecycle-state'
	}
	if ($Name -match '^\w+_export_') {
		return 'export-file'
	}
	if ($Name -match '(wavefunction|spinor|matrix|vector|density|bloch|state|gate|pauli|kron|eigen|diagonal|determinant|array|curve|spectrum|levels|bands|trajectory)') {
		return 'array-matrix-state'
	}
	if ($Name -match '(solver|integrat|evolution|propagat|path_integral|numerical|fft|runge|rk4|convergence)') {
		return 'numerical-solver'
	}
	if ($Name -match '(buffer|output|list_|allowed_|compute_)') {
		return 'buffer-or-enumeration'
	}
	if ($Name -match '^\w+_(get_|set_|create|destroy)') {
		return 'lifecycle-state'
	}
	return 'scalar-domain'
}

$report = [System.Collections.Generic.List[string]]::new()
$categoryReport = [System.Collections.Generic.List[string]]::new()
$report.Add('# Phase 10 C API Inventory')
$report.Add('')
$report.Add('Generated by `scripts/audit-c-api.ps1`. The parser uses balanced function signatures and reports names visible in headers and wrapper sources.')
$report.Add('')
$report.Add('| Module | Header | Source | Declarations | Definitions | Missing definitions | Extra definitions |')
$report.Add('|---|---|---|---:|---:|---:|---:|')

foreach ($module in $modules) {
	$repo = Join-Path (Resolve-Path $ReposRoot) $module.Name
	$headerPath = Join-Path $repo $module.Header
	if (-not (Test-Path -LiteralPath $headerPath)) {
		$headerPath = Join-Path $projectRoot 'fluid_c_api.h'
	}
	$sourcePath = Join-Path $repo $module.Source

	if (-not (Test-Path -LiteralPath $headerPath)) {
		throw "Missing API header for $($module.Name): $headerPath"
	}
	if (-not (Test-Path -LiteralPath $sourcePath)) {
		throw "Missing API source for $($module.Name): $sourcePath"
	}

	$declarations = @(Get-FunctionNames $headerPath Declaration)
	$definitions = @(Get-FunctionNames $sourcePath Definition)
	$missing = @($declarations | Where-Object { $_ -notin $definitions })
	$extra = @($definitions | Where-Object { $_ -notin $declarations })
	$categories = @{}
	foreach ($declaration in $declarations) {
		$category = Get-ApiCategory $declaration
		if (-not $categories.ContainsKey($category)) { $categories[$category] = [System.Collections.Generic.List[string]]::new() }
		$categories[$category].Add($declaration)
	}

	$report.Add("| $($module.Name) | ``$($module.Header)`` | ``$($module.Source)`` | $($declarations.Count) | $($definitions.Count) | $($missing.Count) | $($extra.Count) |")
	$report.Add('')
	$report.Add("## $($module.Name)")
	$report.Add('')
	$report.Add("- Declarations: $($declarations -join ', ')")
	$report.Add("- Definitions: $($definitions -join ', ')")
	$report.Add("- Missing definitions: $(if ($missing.Count) { $missing -join ', ' } else { 'none' })")
	$report.Add("- Extra definitions: $(if ($extra.Count) { $extra -join ', ' } else { 'none' })")
	$report.Add('')
	$categoryReport.Add("## $($module.Name)")
	$categoryReport.Add('')
	$categoryReport.Add('| Category | Count | APIs |')
	$categoryReport.Add('|---|---:|---|')
	foreach ($category in ($categories.Keys | Sort-Object)) {
		$categoryReport.Add("| $category | $($categories[$category].Count) | $($categories[$category] -join ', ') |")
	}
	$categoryReport.Add('')
}

$parent = Split-Path -Parent $OutputPath
New-Item -ItemType Directory -Force -Path $parent | Out-Null
Set-Content -LiteralPath $OutputPath -Value $report -Encoding UTF8
$categoryParent = Split-Path -Parent $CategoryOutputPath
New-Item -ItemType Directory -Force -Path $categoryParent | Out-Null
$categoryHeader = @(
	'# Phase 10 API Categories',
	'',
	'Generated by `scripts/audit-c-api.ps1`. Each exported declaration is assigned exactly one review category using ordered name-based rules.',
	'',
	'Categories are planning groups, not scientific validation results. APIs still require domain-specific reference tests before Phase 10 can close.',
	''
)
Set-Content -LiteralPath $CategoryOutputPath -Value ($categoryHeader + $categoryReport) -Encoding UTF8
Write-Output "Wrote $OutputPath"
Write-Output "Wrote $CategoryOutputPath"
